use std::env;
use std::ffi::OsStr;
use std::fs::File;
use std::io::{self, BufWriter, IsTerminal, Read, Write};
use std::path::PathBuf;
use std::process::ExitCode;

use anstream::{AutoStream, ColorChoice as StreamColorChoice};
use clap::{Parser as ClapParser, ValueEnum};
use flon::{
    Config, ConfirmedOutput, EventOutcome, Formatter, InvalidCandidatePolicy, KeyOverflowPolicy,
    OutputMode, Recovery, Styling,
};
use json_skimmer::Parser;

const INFINITE_MEMORY_BYTES: u64 = 512 * 1024 * 1024;

#[derive(ClapParser, Debug)]
#[command(version, about = "Stream JSON as flat, grep-friendly assignments")]
struct Cli {
    /// Read JSON from FILE; omit FILE or use '-' for stdin.
    input: Option<PathBuf>,

    /// Apply named defaults; explicit options override the profile.
    #[arg(long, value_enum)]
    profile: Option<Profile>,

    /// Action to take when a malformed JSON candidate is found.
    #[arg(long, value_enum)]
    invalid: Option<InvalidAction>,

    /// Maximum raw bytes retained for one object key.
    #[arg(long, value_parser = parse_size)]
    max_key_bytes: Option<u64>,

    /// Action to take when an object key exceeds its byte limit.
    #[arg(long, value_enum)]
    key_overflow: Option<KeyOverflowAction>,

    /// Write live or only after a candidate is confirmed valid.
    #[arg(long, value_enum)]
    output_mode: Option<OutputModeArg>,

    /// Bytes retained in memory before confirmed output spills to a file.
    #[arg(long, value_parser = parse_size)]
    confirmed_memory: Option<u64>,

    /// Maximum generated bytes buffered per candidate, or 'unlimited'.
    #[arg(long, value_parser = parse_limit)]
    confirmed_limit: Option<ConfirmedLimit>,

    /// Directory in which confirmed-output spill files are created.
    #[arg(long)]
    spool_directory: Option<PathBuf>,

    /// Recovery diagnostics destination.
    #[arg(long, value_enum)]
    diagnostics: Option<Diagnostics>,

    /// When to emit terminal colors.
    #[arg(long, value_enum, conflicts_with = "no_color")]
    color: Option<ColorChoice>,

    /// Disable terminal colors (alias for --color=never).
    #[arg(long, conflicts_with = "color")]
    no_color: bool,

    /// Print the resolved configuration and exit.
    #[arg(long)]
    show_config: bool,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq, ValueEnum)]
enum Profile {
    /// Live output, silent recovery, and no diagnostics.
    Wraith,
    /// Confirmed output, unlimited spool, annotated recovery, and diagnostics.
    Infinite,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq, ValueEnum)]
enum InvalidAction {
    Fail,
    Skip,
    Comment,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq, ValueEnum)]
enum KeyOverflowAction {
    Error,
    Skip,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq, ValueEnum)]
enum OutputModeArg {
    Live,
    Confirmed,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq, ValueEnum)]
enum Diagnostics {
    Stderr,
    Quiet,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq, ValueEnum)]
enum ColorChoice {
    Auto,
    Always,
    Never,
}

impl ColorChoice {
    fn stream_choice(self, is_terminal: bool) -> StreamColorChoice {
        match self {
            Self::Auto if is_terminal => StreamColorChoice::Always,
            Self::Auto => StreamColorChoice::Never,
            Self::Always => StreamColorChoice::AlwaysAnsi,
            Self::Never => StreamColorChoice::Never,
        }
    }
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
enum ConfirmedLimit {
    Bytes(u64),
    Unlimited,
}

#[derive(Debug)]
struct EffectiveConfig {
    formatter: Config,
    diagnostics: Diagnostics,
    color: ColorChoice,
}

fn main() -> ExitCode {
    let cli = Cli::parse();
    match run(cli) {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) if error.kind() == io::ErrorKind::BrokenPipe => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("flon: {error}");
            ExitCode::FAILURE
        }
    }
}

fn run(cli: Cli) -> io::Result<()> {
    let effective = resolve(&cli);
    if cli.show_config {
        println!("{effective:#?}");
        return Ok(());
    }

    let mut input: Box<dyn Read> = match cli.input.as_deref() {
        None => Box::new(io::stdin()),
        Some(path) if path.as_os_str() == OsStr::new("-") => Box::new(io::stdin()),
        Some(path) => Box::new(File::open(path)?),
    };

    let stdout = io::stdout();
    let stream_choice = effective.color.stream_choice(stdout.is_terminal());
    let output = AutoStream::new(stdout.lock(), stream_choice);
    let output = BufWriter::new(output);
    let mut output = format_stream(&mut input, output, effective)?;
    output.flush()
}

fn resolve(cli: &Cli) -> EffectiveConfig {
    let mut formatter = Config::default();
    let mut diagnostics = Diagnostics::Stderr;

    match cli.profile {
        Some(Profile::Wraith) => {
            formatter.invalid_candidate = InvalidCandidatePolicy::Skip;
            formatter.output_mode = OutputMode::Live;
            diagnostics = Diagnostics::Quiet;
        }
        Some(Profile::Infinite) => {
            formatter.invalid_candidate = InvalidCandidatePolicy::SkipWithComment;
            formatter.output_mode = OutputMode::Confirmed(ConfirmedOutput {
                memory_threshold: INFINITE_MEMORY_BYTES,
                candidate_limit: None,
                spool_directory: None,
            });
            diagnostics = Diagnostics::Stderr;
        }
        None => {}
    }

    if let Some(invalid) = cli.invalid {
        formatter.invalid_candidate = match invalid {
            InvalidAction::Fail => InvalidCandidatePolicy::Fail,
            InvalidAction::Skip => InvalidCandidatePolicy::Skip,
            InvalidAction::Comment => InvalidCandidatePolicy::SkipWithComment,
        };
    }
    if let Some(maximum) = cli.max_key_bytes {
        formatter.max_key_bytes = usize::try_from(maximum).unwrap_or(usize::MAX);
    }
    if let Some(overflow) = cli.key_overflow {
        formatter.key_overflow = match overflow {
            KeyOverflowAction::Error => KeyOverflowPolicy::Error,
            KeyOverflowAction::Skip => KeyOverflowPolicy::SkipValue,
        };
    }
    if let Some(selected) = cli.output_mode {
        match selected {
            OutputModeArg::Live => formatter.output_mode = OutputMode::Live,
            OutputModeArg::Confirmed => {
                if matches!(formatter.output_mode, OutputMode::Live) {
                    formatter.output_mode = OutputMode::Confirmed(ConfirmedOutput::default());
                }
            }
        }
    }

    let confirmed_option_selected = cli.confirmed_memory.is_some()
        || cli.confirmed_limit.is_some()
        || cli.spool_directory.is_some();
    if confirmed_option_selected
        && cli.output_mode != Some(OutputModeArg::Live)
        && matches!(formatter.output_mode, OutputMode::Live)
    {
        formatter.output_mode = OutputMode::Confirmed(ConfirmedOutput::default());
    }
    if let OutputMode::Confirmed(confirmed) = &mut formatter.output_mode {
        if let Some(memory) = cli.confirmed_memory {
            confirmed.memory_threshold = memory;
        }
        if let Some(limit) = cli.confirmed_limit {
            confirmed.candidate_limit = match limit {
                ConfirmedLimit::Bytes(bytes) => Some(bytes),
                ConfirmedLimit::Unlimited => None,
            };
        }
        if let Some(directory) = &cli.spool_directory {
            confirmed.spool_directory = Some(directory.clone());
        }
    }
    if let Some(selected) = cli.diagnostics {
        diagnostics = selected;
    }

    let color = resolve_color(cli);
    formatter.styling = if color == ColorChoice::Never {
        Styling::Plain
    } else {
        Styling::Ansi
    };

    EffectiveConfig {
        formatter,
        diagnostics,
        color,
    }
}

fn resolve_color(cli: &Cli) -> ColorChoice {
    if cli.no_color {
        return ColorChoice::Never;
    }
    if let Some(color) = cli.color {
        return color;
    }
    if let Some(color) = env::var_os("FLON_COLOR").and_then(|value| parse_color_env(&value)) {
        return color;
    }
    if env::var_os("NO_COLOR").is_some() {
        return ColorChoice::Never;
    }
    if env_requests_color("FORCE_COLOR") || env_requests_color("CLICOLOR_FORCE") {
        return ColorChoice::Always;
    }
    if env::var_os("CLICOLOR").is_some_and(|value| value == "0")
        || env::var_os("TERM").is_some_and(|value| value.eq_ignore_ascii_case("dumb"))
    {
        return ColorChoice::Never;
    }
    ColorChoice::Auto
}

fn parse_color_env(value: &OsStr) -> Option<ColorChoice> {
    match value.to_str()?.to_ascii_lowercase().as_str() {
        "auto" => Some(ColorChoice::Auto),
        "always" => Some(ColorChoice::Always),
        "never" => Some(ColorChoice::Never),
        _ => None,
    }
}

fn env_requests_color(name: &str) -> bool {
    env::var_os(name).is_some_and(|value| !value.is_empty() && value != "0")
}

fn format_stream<R: Read, W: Write>(
    mut input: R,
    output: W,
    effective: EffectiveConfig,
) -> io::Result<W> {
    let mut parser = Parser::default();
    let mut formatter = Formatter::with_config(output, effective.formatter);
    let mut buffer = [0_u8; 8 * 1024];

    loop {
        let count = input.read(&mut buffer)?;
        if count == 0 {
            break;
        }
        let mut error = None;
        parser.push(&buffer[..count], |event| {
            if error.is_none() {
                match formatter.event_with_outcome(event) {
                    Ok(EventOutcome::None) => {}
                    Ok(EventOutcome::Recovered(recovery)) => {
                        report_recovery(&recovery, effective.diagnostics);
                    }
                    Err(found) => error = Some(found),
                }
            }
        });
        if let Some(error) = error {
            return Err(error);
        }
    }

    let mut error = None;
    parser.finish(|event| match formatter.event_with_outcome(event) {
        Ok(EventOutcome::None) => {}
        Ok(EventOutcome::Recovered(recovery)) => {
            report_recovery(&recovery, effective.diagnostics);
        }
        Err(found) => error = Some(found),
    });
    if let Some(error) = error {
        return Err(error);
    }
    Ok(formatter.into_inner())
}

fn report_recovery(recovery: &Recovery, diagnostics: Diagnostics) {
    if diagnostics == Diagnostics::Quiet {
        return;
    }
    let storage = if recovery.spilled_to_file {
        " (spilled to file)"
    } else {
        ""
    };
    eprintln!(
        "flon: discarded {} confirmed-output bytes{storage}; {:?} at byte {}; scanning for next candidate",
        recovery.discarded_output_bytes, recovery.error.kind, recovery.error.offset
    );
}

fn parse_limit(value: &str) -> Result<ConfirmedLimit, String> {
    if value.eq_ignore_ascii_case("unlimited") {
        Ok(ConfirmedLimit::Unlimited)
    } else {
        parse_size(value).map(ConfirmedLimit::Bytes)
    }
}

fn parse_size(value: &str) -> Result<u64, String> {
    let normalized = value.trim();
    let split = normalized
        .find(|character: char| !character.is_ascii_digit())
        .unwrap_or(normalized.len());
    let (digits, suffix) = normalized.split_at(split);
    let amount = digits
        .parse::<u64>()
        .map_err(|_| format!("invalid size: {value}"))?;
    let multiplier = match suffix.to_ascii_lowercase().as_str() {
        "" | "b" => 1,
        "kib" => 1024,
        "mib" => 1024 * 1024,
        "gib" => 1024 * 1024 * 1024,
        _ => {
            return Err(format!(
                "unsupported size suffix in {value}; use B, KiB, MiB, or GiB"
            ));
        }
    };
    amount
        .checked_mul(multiplier)
        .ok_or_else(|| format!("size is too large: {value}"))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn cli(arguments: &[&str]) -> Cli {
        Cli::try_parse_from(std::iter::once("flon").chain(arguments.iter().copied()))
            .expect("parse CLI")
    }

    #[test]
    fn parses_binary_sizes_and_unlimited() {
        assert_eq!(parse_size("128MiB"), Ok(128 * 1024 * 1024));
        assert_eq!(parse_size("10GiB"), Ok(10 * 1024 * 1024 * 1024));
        assert_eq!(parse_limit("unlimited"), Ok(ConfirmedLimit::Unlimited));
        assert!(parse_size("12MB").is_err());
    }

    #[test]
    fn wraith_is_live_quiet_and_skips() {
        let effective = resolve(&cli(&["--profile", "wraith"]));
        assert_eq!(effective.formatter.output_mode, OutputMode::Live);
        assert_eq!(
            effective.formatter.invalid_candidate,
            InvalidCandidatePolicy::Skip
        );
        assert_eq!(effective.diagnostics, Diagnostics::Quiet);
    }

    #[test]
    fn infinite_is_confirmed_unlimited_and_annotates() {
        let effective = resolve(&cli(&["--profile", "infinite"]));
        assert_eq!(
            effective.formatter.invalid_candidate,
            InvalidCandidatePolicy::SkipWithComment
        );
        assert_eq!(effective.diagnostics, Diagnostics::Stderr);
        let OutputMode::Confirmed(confirmed) = effective.formatter.output_mode else {
            panic!("infinite profile should select confirmed output");
        };
        assert_eq!(confirmed.memory_threshold, INFINITE_MEMORY_BYTES);
        assert_eq!(confirmed.candidate_limit, None);
    }

    #[test]
    fn explicit_options_override_profiles() {
        let effective = resolve(&cli(&[
            "--profile",
            "infinite",
            "--output-mode",
            "live",
            "--invalid",
            "fail",
            "--diagnostics",
            "quiet",
        ]));
        assert_eq!(effective.formatter.output_mode, OutputMode::Live);
        assert_eq!(
            effective.formatter.invalid_candidate,
            InvalidCandidatePolicy::Fail
        );
        assert_eq!(effective.diagnostics, Diagnostics::Quiet);
    }

    #[test]
    fn explicit_live_mode_wins_over_confirmed_tuning() {
        let effective = resolve(&cli(&[
            "--profile",
            "infinite",
            "--output-mode",
            "live",
            "--confirmed-memory",
            "4MiB",
        ]));
        assert_eq!(effective.formatter.output_mode, OutputMode::Live);
    }

    #[test]
    fn key_limits_are_exposed_by_the_cli() {
        let effective = resolve(&cli(&["--max-key-bytes", "1MiB", "--key-overflow", "skip"]));
        assert_eq!(effective.formatter.max_key_bytes, 1024 * 1024);
        assert_eq!(
            effective.formatter.key_overflow,
            KeyOverflowPolicy::SkipValue
        );
    }

    #[test]
    fn explicit_color_modes_control_formatter_styling() {
        let colored = resolve(&cli(&["--color", "always"]));
        assert_eq!(colored.color, ColorChoice::Always);
        assert_eq!(colored.formatter.styling, Styling::Ansi);

        let plain = resolve(&cli(&["--no-color"]));
        assert_eq!(plain.color, ColorChoice::Never);
        assert_eq!(plain.formatter.styling, Styling::Plain);
    }

    #[test]
    fn parses_flon_color_environment_values() {
        assert_eq!(parse_color_env(OsStr::new("auto")), Some(ColorChoice::Auto));
        assert_eq!(
            parse_color_env(OsStr::new("ALWAYS")),
            Some(ColorChoice::Always)
        );
        assert_eq!(
            parse_color_env(OsStr::new("never")),
            Some(ColorChoice::Never)
        );
        assert_eq!(parse_color_env(OsStr::new("sometimes")), None);
    }

    #[test]
    fn confirmed_tuning_selects_confirmed_mode() {
        let effective = resolve(&cli(&[
            "--confirmed-memory",
            "4MiB",
            "--confirmed-limit",
            "2GiB",
        ]));
        let OutputMode::Confirmed(confirmed) = effective.formatter.output_mode else {
            panic!("confirmed tuning should select confirmed output");
        };
        assert_eq!(confirmed.memory_threshold, 4 * 1024 * 1024);
        assert_eq!(confirmed.candidate_limit, Some(2 * 1024 * 1024 * 1024));
    }
}
