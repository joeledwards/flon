//! Streaming conversion from JSON to flat object notation.

use std::fs::File;
use std::io::{self, Read, Seek, Write};
use std::num::{NonZeroU64, NonZeroUsize};
use std::path::{Path, PathBuf};

use anstyle::{Ansi256Color, AnsiColor, Style};
use json_skimmer::{ContainerKind, ErrorKind, Event, ParseError, Parser, StringKind};

/// Default maximum number of raw JSON bytes retained for one object key.
pub const DEFAULT_MAX_KEY_BYTES: usize = 64 * 1024;
pub const DEFAULT_CONFIRMED_MEMORY_BYTES: u64 = 128 * 1024 * 1024;
pub const DEFAULT_CONFIRMED_LIMIT_BYTES: u64 = 10 * 1024 * 1024 * 1024;

/// Action taken when an object key exceeds [`Config::max_key_bytes`].
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum KeyOverflowPolicy {
    /// Stop formatting and return an error.
    Error,
    /// Validate the rest of the key and skip its complete associated value.
    SkipValue,
}

/// Action taken when `json-skimmer` reports an invalid JSON candidate.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum InvalidCandidatePolicy {
    /// Stop formatting and return an error.
    Fail,
    /// Reset candidate state and continue scanning without an annotation.
    Skip,
    /// Reset, continue scanning, and write a JavaScript block comment.
    SkipWithComment,
}

/// Storage policy for output awaiting candidate confirmation.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ConfirmedOutput {
    /// Bytes retained in memory before spilling the candidate to a file.
    pub memory_threshold: u64,
    /// Maximum generated bytes for one candidate, or `None` for unlimited.
    pub candidate_limit: Option<u64>,
    /// Optional directory in which private spill files are created.
    pub spool_directory: Option<PathBuf>,
}

impl Default for ConfirmedOutput {
    fn default() -> Self {
        Self {
            memory_threshold: DEFAULT_CONFIRMED_MEMORY_BYTES,
            candidate_limit: Some(DEFAULT_CONFIRMED_LIMIT_BYTES),
            spool_directory: None,
        }
    }
}

/// When generated FLON becomes visible to the output destination.
#[derive(Clone, Debug, Default, Eq, PartialEq)]
pub enum OutputMode {
    /// Write every assignment immediately.
    #[default]
    Live,
    /// Release a top-level candidate only after successful parsing.
    Confirmed(ConfirmedOutput),
}

/// Whether the formatter emits semantic ANSI styles.
#[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]
pub enum Styling {
    #[default]
    Plain,
    Ansi,
}

/// Resource limits and overflow behavior for a formatter.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct Config {
    /// Maximum open containers in the stream adapters, including the root.
    /// Callers feeding events directly must configure their parser separately.
    pub max_depth: NonZeroUsize,
    /// Maximum raw input bytes per candidate in stream adapters; `None` is unlimited.
    /// Direct event consumers must configure their parser separately.
    pub max_candidate_bytes: Option<NonZeroU64>,
    /// Maximum raw bytes retained for one object key.
    pub max_key_bytes: usize,
    pub key_overflow: KeyOverflowPolicy,
    pub invalid_candidate: InvalidCandidatePolicy,
    pub output_mode: OutputMode,
    pub styling: Styling,
}

impl Default for Config {
    fn default() -> Self {
        Self {
            max_depth: json_skimmer::DEFAULT_MAX_DEPTH,
            max_candidate_bytes: None,
            max_key_bytes: DEFAULT_MAX_KEY_BYTES,
            key_overflow: KeyOverflowPolicy::Error,
            invalid_candidate: InvalidCandidatePolicy::Fail,
            output_mode: OutputMode::Live,
            styling: Styling::Plain,
        }
    }
}

/// Details about an invalid candidate that FLON skipped.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct Recovery {
    pub error: ParseError,
    /// Generated bytes discarded from confirmed storage.
    pub discarded_output_bytes: u64,
    pub spilled_to_file: bool,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub enum EventOutcome {
    None,
    Recovered(Recovery),
}

/// Incrementally translates `json-skimmer` events into FLON assignments.
pub struct Formatter<W> {
    output: Output<W>,
    config: Config,
    stack: Vec<Frame>,
    string: Option<ActiveString>,
    number: Option<bool>,
    root_written: bool,
    candidate_root_written: bool,
}

#[derive(Debug)]
struct Frame {
    kind: ContainerKind,
    component: Option<Component>,
    key: Option<PendingKey>,
    next_index: u64,
    suppressed: bool,
}

#[derive(Debug)]
enum Component {
    Key(Vec<u8>),
    Index(u64),
}

#[derive(Debug)]
enum PendingKey {
    Buffered(Vec<u8>),
    Skip,
}

enum ActiveString {
    Key(Vec<u8>),
    OverflowedKey,
    DiscardedKey,
    Value { emitted: bool },
}

enum ValueTarget {
    Emit(Component),
    Skip,
}

#[derive(Clone, Copy)]
enum SemanticStyle {
    Root,
    Key,
    Index,
    String,
    Number,
    Boolean,
    Null,
}

impl SemanticStyle {
    const fn style(self) -> Style {
        match self {
            Self::Root | Self::Key => AnsiColor::Blue.on_default(),
            Self::Index | Self::Number => Ansi256Color(208).on_default(),
            Self::String => AnsiColor::Green.on_default(),
            Self::Boolean => AnsiColor::Magenta.on_default(),
            Self::Null => AnsiColor::Yellow.on_default(),
        }
    }
}

enum Output<W> {
    Live(W),
    Confirmed {
        destination: W,
        config: ConfirmedOutput,
        candidate: CandidateBuffer,
    },
}

enum CandidateBuffer {
    Inactive,
    Memory(Vec<u8>),
    File { file: File, len: u64 },
}

impl CandidateBuffer {
    fn len(&self) -> u64 {
        match self {
            Self::Inactive => 0,
            Self::Memory(bytes) => bytes.len() as u64,
            Self::File { len, .. } => *len,
        }
    }

    fn spilled(&self) -> bool {
        matches!(self, Self::File { .. })
    }
}

impl<W: Write> Output<W> {
    fn new(destination: W, mode: &OutputMode) -> Self {
        match mode {
            OutputMode::Live => Self::Live(destination),
            OutputMode::Confirmed(config) => Self::Confirmed {
                destination,
                config: config.clone(),
                candidate: CandidateBuffer::Inactive,
            },
        }
    }

    fn into_inner(self) -> W {
        match self {
            Self::Live(destination) | Self::Confirmed { destination, .. } => destination,
        }
    }

    fn is_confirmed(&self) -> bool {
        matches!(self, Self::Confirmed { .. })
    }

    fn begin_candidate(&mut self) {
        if let Self::Confirmed { candidate, .. } = self {
            *candidate = CandidateBuffer::Memory(Vec::new());
        }
    }

    fn commit_candidate(&mut self) -> io::Result<()> {
        let Self::Confirmed {
            destination,
            candidate,
            ..
        } = self
        else {
            return Ok(());
        };

        match std::mem::replace(candidate, CandidateBuffer::Inactive) {
            CandidateBuffer::Inactive => Err(invalid_events()),
            CandidateBuffer::Memory(bytes) => destination.write_all(&bytes),
            CandidateBuffer::File { mut file, .. } => {
                file.rewind()?;
                io::copy(&mut file, destination)?;
                Ok(())
            }
        }
    }

    fn discard_candidate(&mut self) -> (u64, bool) {
        match self {
            Self::Live(_) => (0, false),
            Self::Confirmed { candidate, .. } => {
                let result = (candidate.len(), candidate.spilled());
                *candidate = CandidateBuffer::Inactive;
                result
            }
        }
    }

    fn write_direct(&mut self, bytes: &[u8]) -> io::Result<()> {
        match self {
            Self::Live(destination) | Self::Confirmed { destination, .. } => {
                destination.write_all(bytes)
            }
        }
    }
}

impl<W: Write> Write for Output<W> {
    fn write(&mut self, bytes: &[u8]) -> io::Result<usize> {
        match self {
            Self::Live(destination) => destination.write(bytes),
            Self::Confirmed {
                config, candidate, ..
            } => {
                let current = candidate.len();
                let next = current.checked_add(bytes.len() as u64).ok_or_else(|| {
                    io::Error::new(io::ErrorKind::OutOfMemory, "confirmed output size overflow")
                })?;
                if config.candidate_limit.is_some_and(|limit| next > limit) {
                    return Err(io::Error::new(
                        io::ErrorKind::OutOfMemory,
                        "confirmed output exceeds configured candidate limit",
                    ));
                }

                if matches!(candidate, CandidateBuffer::Memory(_)) && next > config.memory_threshold
                {
                    let mut file = create_spool_file(config.spool_directory.as_deref())?;
                    if let CandidateBuffer::Memory(buffered) = candidate {
                        file.write_all(buffered)?;
                    }
                    *candidate = CandidateBuffer::File { file, len: current };
                }

                match candidate {
                    CandidateBuffer::Inactive => Err(invalid_events()),
                    CandidateBuffer::Memory(buffered) => {
                        buffered.extend_from_slice(bytes);
                        Ok(bytes.len())
                    }
                    CandidateBuffer::File { file, len } => {
                        file.write_all(bytes)?;
                        *len = next;
                        Ok(bytes.len())
                    }
                }
            }
        }
    }

    fn flush(&mut self) -> io::Result<()> {
        match self {
            Self::Live(destination) | Self::Confirmed { destination, .. } => destination.flush(),
        }
    }
}

fn create_spool_file(directory: Option<&Path>) -> io::Result<File> {
    match directory {
        Some(directory) => tempfile::tempfile_in(directory),
        None => tempfile::tempfile(),
    }
}

fn write_direct<W: Write>(
    output: &mut Output<W>,
    arguments: std::fmt::Arguments<'_>,
) -> io::Result<()> {
    output.write_direct(arguments.to_string().as_bytes())
}

impl<W: Write> Formatter<W> {
    pub fn new(output: W) -> Self {
        Self::with_config(output, Config::default())
    }

    pub fn with_config(output: W, config: Config) -> Self {
        let output = Output::new(output, &config.output_mode);
        Self {
            output,
            config,
            stack: Vec::new(),
            string: None,
            number: None,
            root_written: false,
            candidate_root_written: false,
        }
    }

    pub fn into_inner(self) -> W {
        self.output.into_inner()
    }

    /// Handles one parser event, discarding any recovery notification.
    pub fn event(&mut self, event: Event<'_>) -> io::Result<()> {
        self.event_with_outcome(event).map(|_| ())
    }

    /// Handles one event and reports when an invalid candidate was skipped.
    pub fn event_with_outcome(&mut self, event: Event<'_>) -> io::Result<EventOutcome> {
        match event {
            Event::CandidateStart { .. } => {
                self.reset_candidate();
                self.candidate_root_written = self.root_written;
                self.output.begin_candidate();
            }
            Event::ObjectStart { .. } => self.open(ContainerKind::Object)?,
            Event::ArrayStart { .. } => self.open(ContainerKind::Array)?,
            Event::ObjectEnd { .. } => self.close(ContainerKind::Object)?,
            Event::ArrayEnd { .. } => self.close(ContainerKind::Array)?,
            Event::StringStart {
                kind: StringKind::Key,
                ..
            } => {
                let frame = self.stack.last().ok_or_else(invalid_events)?;
                if frame.kind != ContainerKind::Object {
                    return Err(invalid_events());
                }
                self.string = Some(if frame.suppressed {
                    ActiveString::DiscardedKey
                } else {
                    ActiveString::Key(Vec::new())
                });
            }
            Event::StringStart {
                kind: StringKind::Value,
                ..
            } => {
                let emitted = self.begin_scalar()?;
                if emitted {
                    self.output.write_all(b"\"")?;
                    write_style_start(
                        &mut self.output,
                        self.config.styling,
                        SemanticStyle::String,
                    )?;
                }
                self.string = Some(ActiveString::Value { emitted });
            }
            Event::StringFragment { kind, bytes, .. } => self.string_fragment(kind, bytes)?,
            Event::StringEnd { kind, .. } => self.end_string(kind)?,
            Event::NumberStart { .. } => {
                let emitted = self.begin_scalar()?;
                if emitted {
                    write_style_start(
                        &mut self.output,
                        self.config.styling,
                        SemanticStyle::Number,
                    )?;
                }
                self.number = Some(emitted);
            }
            Event::NumberFragment { bytes, .. } => match self.number {
                Some(true) => self.output.write_all(bytes)?,
                Some(false) => {}
                None => return Err(invalid_events()),
            },
            Event::NumberEnd { .. } => match self.number.take() {
                Some(true) => {
                    write_style_end(&mut self.output, self.config.styling, SemanticStyle::Number)?;
                    self.output.write_all(b";\n")?;
                }
                Some(false) => {}
                None => return Err(invalid_events()),
            },
            Event::Boolean { value, .. } => {
                self.scalar(
                    if value { b"true" } else { b"false" },
                    SemanticStyle::Boolean,
                )?;
            }
            Event::Null { .. } => self.scalar(b"null", SemanticStyle::Null)?,
            Event::Invalid(error) => return self.invalid_candidate(error),
            Event::CandidateEnd { .. } => {
                self.output.commit_candidate()?;
                self.reset_candidate();
            }
        }
        Ok(EventOutcome::None)
    }

    fn reset_candidate(&mut self) {
        self.stack.clear();
        self.string = None;
        self.number = None;
    }

    fn invalid_candidate(&mut self, error: ParseError) -> io::Result<EventOutcome> {
        let (discarded_output_bytes, spilled_to_file) = self.output.discard_candidate();
        if self.output.is_confirmed() {
            self.root_written = self.candidate_root_written;
        }
        match self.config.invalid_candidate {
            InvalidCandidatePolicy::Fail => return Err(parse_error(&error)),
            InvalidCandidatePolicy::Skip => {}
            InvalidCandidatePolicy::SkipWithComment => {
                let partial_scalar =
                    matches!(self.string, Some(ActiveString::Value { emitted: true }))
                        || self.number == Some(true);
                if partial_scalar {
                    self.output.write_direct(b"\n")?;
                }
                self.output.write_direct(b"/* flon-error kind=")?;
                self.output
                    .write_direct(error_kind_name(error.kind).as_bytes())?;
                write_direct(&mut self.output, format_args!(" offset={}", error.offset))?;
                if let Some(start) = error.candidate_start {
                    write_direct(&mut self.output, format_args!(" candidate_start={start}"))?;
                } else {
                    self.output.write_direct(b" candidate_start=none")?;
                }
                self.output.write_direct(b" */\n")?;
            }
        }
        self.reset_candidate();
        Ok(EventOutcome::Recovered(Recovery {
            error,
            discarded_output_bytes,
            spilled_to_file,
        }))
    }

    fn open(&mut self, kind: ContainerKind) -> io::Result<()> {
        let component = if self.stack.is_empty() {
            if !self.root_written {
                write_styled(
                    &mut self.output,
                    self.config.styling,
                    SemanticStyle::Root,
                    b"json",
                )?;
                self.output.write_all(b" = ")?;
                self.write_container(kind)?;
                self.output.write_all(b";\n")?;
                self.root_written = true;
            }
            None
        } else {
            match self.take_target()? {
                ValueTarget::Emit(component) => {
                    self.write_path(Some(&component))?;
                    self.output.write_all(b" = ")?;
                    self.write_container(kind)?;
                    self.output.write_all(b";\n")?;
                    Some(component)
                }
                ValueTarget::Skip => None,
            }
        };

        let suppressed = !self.stack.is_empty() && component.is_none();

        self.stack.push(Frame {
            kind,
            component,
            key: None,
            next_index: 0,
            suppressed,
        });
        Ok(())
    }

    fn close(&mut self, expected: ContainerKind) -> io::Result<()> {
        let frame = self.stack.pop().ok_or_else(invalid_events)?;
        if frame.kind != expected {
            return Err(invalid_events());
        }
        Ok(())
    }

    fn end_string(&mut self, kind: StringKind) -> io::Result<()> {
        match (kind, self.string.take()) {
            (StringKind::Key, Some(ActiveString::Key(token))) => {
                let frame = self.stack.last_mut().ok_or_else(invalid_events)?;
                if frame.kind != ContainerKind::Object {
                    return Err(invalid_events());
                }
                frame.key = Some(PendingKey::Buffered(token));
            }
            (StringKind::Key, Some(ActiveString::OverflowedKey | ActiveString::DiscardedKey)) => {
                let frame = self.stack.last_mut().ok_or_else(invalid_events)?;
                if frame.kind != ContainerKind::Object {
                    return Err(invalid_events());
                }
                frame.key = Some(PendingKey::Skip);
            }
            (StringKind::Value, Some(ActiveString::Value { emitted: true })) => {
                write_style_end(&mut self.output, self.config.styling, SemanticStyle::String)?;
                self.output.write_all(b"\";\n")?;
            }
            (StringKind::Value, Some(ActiveString::Value { emitted: false })) => {}
            _ => return Err(invalid_events()),
        }
        Ok(())
    }

    fn string_fragment(&mut self, kind: StringKind, bytes: &[u8]) -> io::Result<()> {
        match (kind, self.string.as_mut()) {
            (StringKind::Key, Some(ActiveString::Key(token))) => {
                if bytes.len() <= self.config.max_key_bytes.saturating_sub(token.len()) {
                    token.extend_from_slice(bytes);
                } else {
                    match self.config.key_overflow {
                        KeyOverflowPolicy::Error => return Err(key_overflow()),
                        KeyOverflowPolicy::SkipValue => {
                            self.string = Some(ActiveString::OverflowedKey);
                        }
                    }
                }
            }
            (StringKind::Key, Some(ActiveString::OverflowedKey | ActiveString::DiscardedKey)) => {}
            (StringKind::Value, Some(ActiveString::Value { emitted: true })) => {
                self.output.write_all(bytes)?;
            }
            (StringKind::Value, Some(ActiveString::Value { emitted: false })) => {}
            _ => return Err(invalid_events()),
        }
        Ok(())
    }

    fn scalar(&mut self, value: &[u8], style: SemanticStyle) -> io::Result<()> {
        if !self.begin_scalar()? {
            return Ok(());
        }
        write_styled(&mut self.output, self.config.styling, style, value)?;
        self.output.write_all(b";\n")
    }

    fn begin_scalar(&mut self) -> io::Result<bool> {
        match self.take_target()? {
            ValueTarget::Emit(component) => {
                self.write_path(Some(&component))?;
                self.output.write_all(b" = ")?;
                Ok(true)
            }
            ValueTarget::Skip => Ok(false),
        }
    }

    fn take_target(&mut self) -> io::Result<ValueTarget> {
        let frame = self.stack.last_mut().ok_or_else(invalid_events)?;
        if frame.suppressed {
            frame.key = None;
            return Ok(ValueTarget::Skip);
        }
        match frame.kind {
            ContainerKind::Object => match frame.key.take().ok_or_else(invalid_events)? {
                PendingKey::Buffered(key) => Ok(ValueTarget::Emit(Component::Key(key))),
                PendingKey::Skip => Ok(ValueTarget::Skip),
            },
            ContainerKind::Array => {
                let index = frame.next_index;
                frame.next_index = frame.next_index.checked_add(1).ok_or_else(|| {
                    io::Error::new(io::ErrorKind::InvalidData, "array index overflow")
                })?;
                Ok(ValueTarget::Emit(Component::Index(index)))
            }
        }
    }

    fn write_path(&mut self, tail: Option<&Component>) -> io::Result<()> {
        write_styled(
            &mut self.output,
            self.config.styling,
            SemanticStyle::Root,
            b"json",
        )?;
        for component in self
            .stack
            .iter()
            .filter_map(|frame| frame.component.as_ref())
        {
            write_component(&mut self.output, self.config.styling, component)?;
        }
        if let Some(component) = tail {
            write_component(&mut self.output, self.config.styling, component)?;
        }
        Ok(())
    }

    fn write_container(&mut self, kind: ContainerKind) -> io::Result<()> {
        self.output.write_all(match kind {
            ContainerKind::Object => b"{}",
            ContainerKind::Array => b"[]",
        })
    }
}

fn write_component(
    output: &mut impl Write,
    styling: Styling,
    component: &Component,
) -> io::Result<()> {
    match component {
        Component::Index(index) => {
            output.write_all(b"[")?;
            write_style_start(output, styling, SemanticStyle::Index)?;
            write!(output, "{index}")?;
            write_style_end(output, styling, SemanticStyle::Index)?;
            output.write_all(b"]")
        }
        Component::Key(key) if is_identifier(key) => {
            output.write_all(b".")?;
            write_styled(output, styling, SemanticStyle::Key, key)
        }
        Component::Key(key) => {
            output.write_all(b"[\"")?;
            write_styled(output, styling, SemanticStyle::Key, key)?;
            output.write_all(b"\"]")
        }
    }
}

fn write_styled(
    output: &mut impl Write,
    styling: Styling,
    semantic: SemanticStyle,
    bytes: &[u8],
) -> io::Result<()> {
    write_style_start(output, styling, semantic)?;
    output.write_all(bytes)?;
    write_style_end(output, styling, semantic)
}

fn write_style_start(
    output: &mut impl Write,
    styling: Styling,
    semantic: SemanticStyle,
) -> io::Result<()> {
    if styling == Styling::Ansi {
        write!(output, "{}", semantic.style())?;
    }
    Ok(())
}

fn write_style_end(
    output: &mut impl Write,
    styling: Styling,
    semantic: SemanticStyle,
) -> io::Result<()> {
    if styling == Styling::Ansi {
        write!(output, "{:#}", semantic.style())?;
    }
    Ok(())
}

fn is_identifier(key: &[u8]) -> bool {
    let Some((&first, rest)) = key.split_first() else {
        return false;
    };
    matches!(first, b'a'..=b'z' | b'A'..=b'Z' | b'_' | b'$')
        && rest
            .iter()
            .all(|byte| matches!(byte, b'a'..=b'z' | b'A'..=b'Z' | b'0'..=b'9' | b'_' | b'$'))
}

fn invalid_events() -> io::Error {
    io::Error::new(
        io::ErrorKind::InvalidData,
        "inconsistent json-skimmer event sequence",
    )
}

fn key_overflow() -> io::Error {
    io::Error::new(
        io::ErrorKind::InvalidData,
        "object key exceeds configured byte limit",
    )
}

fn parse_error(error: &ParseError) -> io::Error {
    let candidate = error
        .candidate_start
        .map_or_else(|| "none".to_owned(), |start| start.to_string());
    io::Error::new(
        io::ErrorKind::InvalidData,
        format!(
            "invalid JSON candidate: {} at byte {} (candidate start: {candidate})",
            error_kind_name(error.kind),
            error.offset
        ),
    )
}

fn error_kind_name(kind: ErrorKind) -> &'static str {
    match kind {
        ErrorKind::UnexpectedByte => "unexpected_byte",
        ErrorKind::InvalidEscape => "invalid_escape",
        ErrorKind::InvalidUnicodeEscape => "invalid_unicode_escape",
        ErrorKind::InvalidUtf8 => "invalid_utf8",
        ErrorKind::DepthLimitExceeded => "depth_limit_exceeded",
        ErrorKind::CandidateLimitExceeded => "candidate_limit_exceeded",
        ErrorKind::ControlCharacterInString => "control_character_in_string",
        ErrorKind::InvalidNumber => "invalid_number",
        ErrorKind::UnexpectedEnd => "unexpected_end",
        ErrorKind::ExpectedSingleValue => "expected_single_value",
        ErrorKind::TrailingData => "trailing_data",
    }
}

/// Reads a stream to EOF and writes plain FLON output.
pub fn format<R: Read, W: Write>(mut input: R, output: W) -> io::Result<W> {
    format_with_config(&mut input, output, Config::default())
}

/// Reads a stream to EOF using the supplied formatter configuration.
pub fn format_with_config<R: Read, W: Write>(
    mut input: R,
    output: W,
    config: Config,
) -> io::Result<W> {
    let mut parser = Parser::with_limits(
        json_skimmer::Mode::Scan,
        config.max_depth,
        config.max_candidate_bytes,
    );
    let mut formatter = Formatter::with_config(output, config);
    let mut buffer = [0_u8; 8 * 1024];

    loop {
        let count = input.read(&mut buffer)?;
        if count == 0 {
            break;
        }
        let mut error = None;
        parser.push(&buffer[..count], |event| {
            if error.is_none() {
                error = formatter.event(event).err();
            }
        });
        if let Some(error) = error {
            return Err(error);
        }
    }

    let mut error = None;
    parser.finish(|event| {
        if error.is_none() {
            error = formatter.event(event).err();
        }
    });
    if let Some(error) = error {
        return Err(error);
    }
    Ok(formatter.into_inner())
}

